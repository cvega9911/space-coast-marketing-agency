#!/usr/bin/env node
// Regenerates dashboard.html with agent_status data embedded inline.
// Also updates agent_status.js as a side-effect (kept for reference).
// Usage: node regen_status.js
// Edit agent_status.json / completed_quests.json to update data, then run this script.

const fs = require('fs');
const path = require('path');
const dir = __dirname;

// --- Read + validate data ---
const data = fs.readFileSync(path.join(dir, 'agent_status.json'), 'utf8');
const parsed = JSON.parse(data); // throws on bad JSON

const questsData = fs.readFileSync(path.join(dir, 'completed_quests.json'), 'utf8');
const parsedQuests = JSON.parse(questsData); // throws on bad JSON

// --- Update agent_status.js (side-effect, kept for reference) ---
const jsOut = `// Auto-generated by regen_status.js — do not edit manually; edit agent_status.json instead.\n// To regenerate: node /home/jarvis/regen_status.js\nwindow.AGENT_STATUS = ${JSON.stringify(parsed)};\n`;
fs.writeFileSync(path.join(dir, 'agent_status.js'), jsOut);
console.log('agent_status.js updated.');

// --- Patch dashboard.html: replace the embedded data block ---
const htmlPath = '/home/jarvis/.openclaw/workspace/dashboard.html';
let html = fs.readFileSync(htmlPath, 'utf8');

const START_MARKER = '/* ---- EMBEDDED AGENT STATUS DATA (auto-generated from agent_status.json) ---- */';
const END_MARKER   = '/* ---- END DATA ---- */';

const startIdx = html.indexOf(START_MARKER);
const endIdx   = html.indexOf(END_MARKER);

if (startIdx === -1 || endIdx === -1) {
  console.error('ERROR: Could not find data markers in dashboard.html.');
  console.error('Expected markers:');
  console.error('  ' + START_MARKER);
  console.error('  ' + END_MARKER);
  process.exit(1);
}

const newBlock = `${START_MARKER}\nwindow.AGENT_STATUS = ${JSON.stringify(parsed)};\nwindow.QUEST_LOG = ${JSON.stringify(parsedQuests)};\n${END_MARKER}`;
html = html.slice(0, startIdx) + newBlock + html.slice(endIdx + END_MARKER.length);

fs.writeFileSync(htmlPath, html);
console.log('dashboard.html updated with embedded agent status data.');
console.log('Timestamp:', parsed.updated || '(no updated field)');
